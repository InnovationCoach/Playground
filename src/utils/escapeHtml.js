// Only for text and quoted attributes in the legacy dashboard templates.
// React views use React's built-in text escaping instead.
export function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, character => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  })[character]);
}
